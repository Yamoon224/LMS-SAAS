const pluralRules = new Intl.PluralRules("ar");

type PluralForms = {
  zero?: string;
  one: string;
  two: string;
  few: string;
  many: string;
  other: string;
};

/** Choisit la forme plurielle arabe ; `{n}` est remplacé par le nombre. Repli sur `other`. */
function plural(n: number, forms: PluralForms): string {
  let category: Intl.LDMLPluralRule = "other";
  try {
    category = pluralRules.select(n);
  } catch {
    category = "other";
  }
  const template = forms[category as keyof PluralForms] ?? forms.other;
  return template.replace("{n}", String(n));
}

